#!/usr/bin/env python3
"""Firmware tables for TopazModem.cpp from this phone's modem partition (a FAT16 NON-HLOS image).

  modem-fwtable.py modem_a.img > out.inc        (spes: backup-spes-20261021/modem_a.img)

TopazModem reads the modem's firmware straight from the partition (sweet_ufs_read_part), so it
needs to know where each file of /image lies: fw_files[] (the modem's own PAS segments, with a
CRC32 that tells whether the partition is still the image the table was made from), and
fw_ext[] + fw_all[] (every file under /image, for the tftp service). Files in several cluster
runs get several extents. Prints the three C arrays, ready to replace topaz' (HyperOS 2.0.208).
"""
import struct, sys, zlib

img = open(sys.argv[1], 'rb').read()
bps, spc, res, nfat, nroot, tot16, media, spf16 = struct.unpack_from('<HBHBHHBH', img, 11)
fat_off = res * bps
root_off = fat_off + nfat * spf16 * bps
data_off = root_off + ((nroot * 32 + bps - 1) // bps) * bps
csize = spc * bps
fat = struct.unpack_from('<%dH' % (spf16 * bps // 2), img, fat_off)


def chain(c):
    out = []
    while 2 <= c < 0xfff8:
        out.append(c)
        c = fat[c]
    return out


def entries(raw):
    lfn = []
    for i in range(0, len(raw), 32):
        e = raw[i:i + 32]
        if e[0] == 0:
            break
        if e[0] == 0xe5:
            lfn = []
            continue
        attr = e[11]
        if attr == 0x0f:
            part = e[1:11] + e[14:26] + e[28:32]
            lfn.insert(0, part.decode('utf-16-le', 'replace').split('\0')[0].rstrip('￿'))
            continue
        if attr & 0x08:
            lfn = []
            continue
        short = e[0:8].decode('latin1').rstrip()
        ext = e[8:11].decode('latin1').rstrip()
        name = ''.join(lfn) if lfn else (short + ('.' + ext if ext else '')).lower()
        lfn = []
        if name in ('.', '..'):
            continue
        clus, size = struct.unpack_from('<H', e, 26)[0], struct.unpack_from('<I', e, 28)[0]
        yield name, attr, clus, size


def walk(raw, prefix):
    for name, attr, clus, size in entries(raw):
        path = prefix + name
        if attr & 0x10:
            data = b''.join(img[data_off + (c - 2) * csize:data_off + (c - 1) * csize] for c in chain(clus))
            yield from walk(data, path + '/')
        else:
            yield path, clus, size


def extents(clus, size):
    runs, left = [], size
    cs = chain(clus)
    i = 0
    while i < len(cs) and left > 0:
        j = i
        while j + 1 < len(cs) and cs[j + 1] == cs[j] + 1:
            j += 1
        off = data_off + (cs[i] - 2) * csize
        ln = min((j - i + 1) * csize, left)
        runs.append((off, ln))
        left -= ln
        i = j + 1
    return runs


files = sorted((p, c, s) for p, c, s in walk(img[root_off:data_off], '') if p.startswith('image/'))
ext, rows, pas = [], [], []
for path, clus, size in files:
    runs = extents(clus, size) if size else []
    rows.append((path, size, len(ext), len(runs)))
    ext += runs
    base = path[len('image/'):]
    if base.startswith('modem.') and '/' not in base:
        if len(runs) != 1:
            sys.exit(f'{path}: {len(runs)} extents; fw_files needs one')
        off, ln = runs[0]
        pas.append((base, off, size, zlib.crc32(img[off:off + size]) & 0xffffffff))

print('/* spes: generated by tools/modem-fwtable.py from this phone\'s modem_a (%d files under /image, %d extents) */'
      % (len(rows), len(ext)))
print('static const struct { const char *name; uint32_t off, size, crc; } fw_files[] = {')
for name, off, size, crc in sorted(pas):
    print('\t{ "%s", %#x, %#x, %#010x },' % (name, off, size, crc))
print('};')
print('static const struct { uint32_t off, len; } fw_ext[] = {')
for off, ln in ext:
    print('\t{ %#x, %#x },' % (off, ln))
print('};')
print('static const struct { const char *path; uint32_t size; uint16_t ext, next; } fw_all[] = {')
for path, size, e, n in rows:
    print('\t{ "%s", %#x, %d, %d },' % (path, size, e, n))
print('};')
